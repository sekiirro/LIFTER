import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const generatedPath = path.join(
  root,
  'lib/staff/display-name-unicode-ranges.ts',
);
const migrationPath = path.join(
  root,
  'supabase/migrations/20261114000000_staff_display_names.sql',
);
const unicodeEscape = String.fromCharCode(92);
const letterOrMark = new RegExp(
  `^[${unicodeEscape}p{L}${unicodeEscape}p{M}]$`,
  'u',
);

function rangesForRuntime() {
  const ranges = [];
  for (let codePoint = 0; codePoint <= 0x10ffff; codePoint += 1) {
    if (!letterOrMark.test(String.fromCodePoint(codePoint))) continue;
    const last = ranges[ranges.length - 1];
    if (last && last[1] + 1 === codePoint) last[1] = codePoint;
    else ranges.push([codePoint, codePoint]);
  }
  return ranges;
}

function renderTypeScript(ranges) {
  const tuples = ranges
    .map(([first, last]) => `  [${first}, ${last}],`)
    .join('\n');
  return `// Generated by scripts/generate-staff-display-name-ranges.mjs. Do not edit.\nexport const STAFF_NAME_UNICODE_VERSION = '${process.versions.unicode}';\nexport const STAFF_NAME_LETTER_MARK_RANGES: readonly (readonly [number, number])[] = [\n${tuples}\n];\n`;
}

function renderSqlMultirange(ranges) {
  return `{${ranges.map(([first, last]) => `[${first},${last + 1})`).join(',')}}`;
}

async function main() {
  const ranges = rangesForRuntime();
  const generated = renderTypeScript(ranges);
  const sqlRanges = renderSqlMultirange(ranges);
  const checkOnly = process.argv.includes('--check');
  if (checkOnly) {
    const [existing, migration] = await Promise.all([
      readFile(generatedPath, 'utf8'),
      readFile(migrationPath, 'utf8'),
    ]);
    if (existing !== generated || !migration.includes(sqlRanges)) {
      throw new Error(
        `Staff-name Unicode allowlist is stale for Node Unicode ${process.versions.unicode}; run this script to regenerate it.`,
      );
    }
    return;
  }

  const migration = await readFile(migrationPath, 'utf8');
  const begin = '/* GENERATED_STAFF_NAME_UNICODE_RANGES_BEGIN */';
  const end = '/* GENERATED_STAFF_NAME_UNICODE_RANGES_END */';
  const startIndex = migration.indexOf(begin);
  const endIndex = migration.indexOf(end);
  if (startIndex < 0 || endIndex < startIndex)
    throw new Error('Migration Unicode range markers are missing.');
  const nextMigration = `${migration.slice(0, startIndex + begin.length)}\n  '${sqlRanges}'::int4multirange${migration.slice(endIndex)}`;
  await Promise.all([
    writeFile(generatedPath, generated),
    writeFile(migrationPath, nextMigration),
  ]);
}

await main();
