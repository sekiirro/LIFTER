// Generator for lib/workout-planner/ai-prompt.ts.
// Copies the approved EN/AR prompt bodies byte-exact from the locale
// contract so the module can never drift from the approved bytes.
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const contractPath = path.join(
  root,
  'specs',
  '017-workout-planner',
  'contracts',
  'copy-ai-prompt.md',
);
const contract = fs.readFileSync(contractPath, 'utf8');
const blocks = [...contract.matchAll(/```\n([\s\S]*?)```/g)].map((m) => m[1]);
if (blocks.length !== 2) {
  throw new Error('expected exactly 2 prompt bodies, found ' + blocks.length);
}
const [en, ar] = blocks;
if (!en.includes('{{PLAN_CONTENT}}') || !ar.includes('{{PLAN_CONTENT}}')) {
  throw new Error('prompt bodies must carry the {{PLAN_CONTENT}} token');
}

const out = `// F17 Copy AI Prompt builder (T008; FR-019, SC-009).
//
// Prompt bodies are copied byte-exact from
// specs/017-workout-planner/contracts/copy-ai-prompt.md (S43-PO-5 approved);
// buildAiPrompt substitutes only the single {{PLAN_CONTENT}} token.
// GENERATED by scripts/gen-ai-prompt.mjs — do not hand-edit the bodies.

export const PLAN_CONTENT_TOKEN = '{{PLAN_CONTENT}}';

export const AI_PROMPT_EN: string = ${JSON.stringify(en)};

export const AI_PROMPT_AR: string = ${JSON.stringify(ar)};

export type AiPromptLocale = 'en' | 'ar';

export function buildAiPrompt(locale: AiPromptLocale, planContent: string): string {
  const template = locale === 'en' ? AI_PROMPT_EN : AI_PROMPT_AR;
  return template.split(PLAN_CONTENT_TOKEN).join(planContent);
}

// Imperative frames that instruct the AI to invent/replace/alter/generate.
// The approved bodies only ever use these verbs under "Do not ...", so the
// "suggest new exercises" frame carries a not-negation lookbehind.
const PROHIBITED = [
  /\\binvent\\b/i,
  /\\bfeel free to (replace|invent|alter|generate|change|add)\\b/i,
  /\\byou may (invent|add|replace|alter|generate|change)\\b/i,
  /\\bgenerate\\b[\\s\\S]{0,60}?\\b(alternatives|exercises)\\b/i,
  /\\balter\\b[\\s\\S]{0,60}?\\bprogramming values\\b/i,
  /(?<!\\bnot )\\bsuggest new exercises\\b/i,
];

export function containsProhibitedInstruction(prompt: string): boolean {
  return PROHIBITED.some((pattern) => pattern.test(prompt));
}
`;

fs.writeFileSync(
  path.join(root, 'lib', 'workout-planner', 'ai-prompt.ts'),
  out,
);
console.log('wrote ai-prompt.ts EN=' + en.length + ' AR=' + ar.length);
